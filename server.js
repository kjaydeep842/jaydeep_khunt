// Verification Endpoint
app.post('/api/payments/verify-payment', async (req, res) => {
  const { gateway, orderId, paymentId, signature, simulated } = req.body;
  console.log(`Verifying payment for ${gateway}...`);

  if (simulated) {
    return res.json({ success: true, verified: true, simulated: true });
  }

  try {
    if (gateway === 'stripe') {
      const stripe = getStripe();
      if (!stripe) throw new Error('Stripe not configured');
      const session = await stripe.checkout.sessions.retrieve(paymentId);
      if (session.payment_status === 'paid') {
        return res.json({ success: true, verified: true });
      }
    } else if (gateway === 'razorpay') {
      const secret = process.env.RAZORPAY_KEY_SECRET;
      if (!secret) throw new Error('Razorpay secret not configured');
      const generated_signature = crypto
        .createHmac('sha256', secret)
        .update(orderId + "|" + paymentId)
        .digest('hex');
      if (generated_signature === signature) {
        return res.json({ success: true, verified: true });
      }
    } else if (gateway === 'cashfree') {
      const appId = process.env.CASHFREE_APP_ID;
      const secretKey = process.env.CASHFREE_SECRET_KEY;
      if (!appId || !secretKey) throw new Error('Cashfree not configured');
      const response = await fetch(`https://sandbox.cashfree.com/pg/orders/${orderId}`, {
        headers: {
          'x-api-version': '2023-08-01',
          'x-client-id': appId,
          'x-client-secret': secretKey,
        }
      });
      const orderData = await response.json();
      if (orderData.order_status === 'PAID') {
        return res.json({ success: true, verified: true });
      }
    } else if (gateway === 'paypal') {
      const clientId = process.env.PAYPAL_CLIENT_ID;
      const clientSecret = process.env.PAYPAL_CLIENT_SECRET;
      if (!clientId || !clientSecret) throw new Error('PayPal not configured');
      
      const auth = Buffer.from(`${clientId}:${clientSecret}`).toString('base64');
      const tokenResponse = await fetch('https://api-m.sandbox.paypal.com/v1/oauth2/token', {
        method: 'POST',
        headers: {
          'Authorization': `Basic ${auth}`,
          'Content-Type': 'application/x-www-form-urlencoded',
        },
        body: 'grant_type=client_credentials',
      });
      const tokenData = await tokenResponse.json();
      const accessToken = tokenData.access_token;

      const captureResponse = await fetch(`https://api-m.sandbox.paypal.com/v2/checkout/orders/${orderId}/capture`, {
        method: 'POST',
        headers: {
          'Authorization': `Bearer ${accessToken}`,
          'Content-Type': 'application/json',
        }
      });
      const captureData = await captureResponse.json();
      if (captureData.status === 'COMPLETED') {
        return res.json({ success: true, verified: true });
      }
    }
    res.status(400).json({ error: 'Signature verification failed' });
  } catch (error) {
    console.error('Verification error:', error);
    res.status(500).json({ error: error.message });
  }
});

