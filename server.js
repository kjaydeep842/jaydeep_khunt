// PayPal Order creation
app.post('/api/payments/create-paypal-order', async (req, res) => {
  const { planName, amount } = req.body;
  const origin = req.headers.origin || 'http://localhost:5173';

  console.log(`Creating PayPal Order for ${planName} (${amount} USD)...`);

  const clientId = process.env.PAYPAL_CLIENT_ID;
  const clientSecret = process.env.PAYPAL_CLIENT_SECRET;

  if (clientId && clientSecret) {
    try {
      // Get Access Token
      const auth = Buffer.from(`${clientId}:${clientSecret}`).toString('base64');
      const tokenResponse = await fetch('https://api-m.sandbox.paypal.com/v1/oauth2/token', {
        method: 'POST',
        headers: {
          'Authorization': `Basic ${auth}`,
          'Content-Type': 'application/x-www-form-urlencoded',
        },
        body: 'grant_type=client_credentials',
      });
      const tokenData = await tokenResponse.json();
      const accessToken = tokenData.access_token;

      // Create Order
      const orderResponse = await fetch('https://api-m.sandbox.paypal.com/v2/checkout/orders', {
        method: 'POST',
        headers: {
          'Authorization': `Bearer ${accessToken}`,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          intent: 'CAPTURE',
          purchase_units: [
            {
              amount: {
                currency_code: 'USD',
                value: amount.toFixed(2),
              },
              description: planName,
            },
          ],
          application_context: {
            brand_name: 'Jaydeep Khunt Portfolio',
            landing_page: 'NO_PREFERENCE',
            user_action: 'PAY_NOW',
            return_url: `${origin}/?payment=success&gateway=paypal&plan=${encodeURIComponent(planName)}&amount=${amount}`,
            cancel_url: `${origin}/?payment=cancel&gateway=paypal`,
          },
        }),
      });

      const orderData = await orderResponse.json();
      const approvalUrl = orderData.links.find((link) => link.rel === 'approve')?.href;

      res.json({ url: approvalUrl, orderId: orderData.id, simulated: false });
    } catch (error) {
      console.error('PayPal error:', error);
      res.status(500).json({ error: error.message });
    }
  } else {
    // Simulated Mode
    const simulatedUrl = `${origin}/?payment=success&gateway=paypal&order_id=pay_sim_${Math.random().toString(36).substring(7)}&plan=${encodeURIComponent(planName)}&amount=${amount}&mode=simulation`;
    res.json({ url: simulatedUrl, simulated: true });
  }
});

